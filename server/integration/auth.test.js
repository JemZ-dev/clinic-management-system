import assert from 'node:assert/strict'
import { randomBytes } from 'node:crypto'
import { once } from 'node:events'
import test from 'node:test'
import mongoose from 'mongoose'
import jwt from 'jsonwebtoken'
import { createApp } from '../src/app.js'
import { connectDatabase, disconnectDatabase, pingDatabase } from '../src/config/db.js'
import { getConfig, loadLocalEnvironment } from '../src/config/env.js'
import { createAuthService } from '../src/services/auth.js'
import { User } from '../src/models/User.js'
import { Session } from '../src/models/Session.js'

test('authentication and profile flow against an isolated Atlas database', async (t) => {
  loadLocalEnvironment()
  const dbName = `clinic_test_${Date.now()}_${randomBytes(6).toString('hex')}`
  const config = {
    jwtSecret: randomBytes(48).toString('hex'), registrationCode: randomBytes(16).toString('hex'),
    appOrigin: 'http://localhost:5173', appOrigins: ['http://localhost:5173', 'http://127.0.0.1:5173'], secureCookies: false,
  }
  let server
  let connected = false
  t.after(async () => {
    if (server) await new Promise((resolve) => server.close(resolve))
    // Cleanup is restricted to the fresh database name generated by this test.
    if (connected && mongoose.connection.name === dbName && /^clinic_test_\d+_[a-f0-9]{12}$/.test(dbName)) {
      await mongoose.connection.dropDatabase()
    }
    await disconnectDatabase()
  })
  await connectDatabase({ ...getConfig(), dbName })
  connected = true
  await Promise.all([User.init(), Session.init()])
  server = createApp({ pingDatabase, config, authService: createAuthService(config) }).listen(0, '127.0.0.1')
  await once(server, 'listening')
  const base = `http://127.0.0.1:${server.address().port}/api/auth`
  const registration = { name: 'Fictional Staff', email: 'staff@example.com', password: 'fictional-long-passphrase', registrationCode: config.registrationCode }
  async function call(path, { method = 'GET', body, cookie, origin = config.appOrigin, customHeader = true } = {}) {
    const headers = { 'Content-Type': 'application/json', Origin: origin }
    if (customHeader) headers['X-Clinic-Request'] = '1'
    if (cookie) headers.Cookie = cookie
    return fetch(`${base}${path}`, { method, headers, ...(body ? { body: JSON.stringify(body) } : {}) })
  }

  assert.equal((await call('/me')).status, 401)
  assert.equal((await call('/login', { method: 'POST', body: {}, origin: 'http://127.0.0.1:5173' })).status, 400, 'loopback alias reaches validation')
  assert.equal((await call('/login', { method: 'POST', body: {}, origin: 'http://localhost:9999' })).status, 403, 'other ports remain blocked')
  assert.equal((await call('/register', { method: 'POST', body: { ...registration, role: 'admin' } })).status, 400)
  assert.equal((await call('/register', { method: 'POST', body: { ...registration, registrationCode: 'incorrect-code' } })).status, 403)
  const created = await call('/register', { method: 'POST', body: registration })
  assert.equal(created.status, 201)
  const data = await created.json()
  assert.equal(data.user.role, 'staff')
  assert.equal(data.user.passwordHash, undefined)
  assert.equal(data.token, undefined)
  const setCookie = created.headers.get('set-cookie')
  assert.match(setCookie, /HttpOnly/i)
  assert.match(setCookie, /SameSite=Strict/i)
  const cookie = setCookie.split(';')[0]
  assert.equal((await call('/me', { cookie })).status, 200)
  const stored = await User.findOne({ email: registration.email }).select('+passwordHash')
  assert.notEqual(stored.passwordHash, registration.password)

  assert.equal((await call('/register', { method: 'POST', body: registration })).status, 409)
  assert.equal((await call('/login', { method: 'POST', body: { email: registration.email, password: 'incorrect-passphrase' } })).status, 401)
  assert.equal((await call('/login', { method: 'POST', body: { email: 'unknown@example.com', password: 'incorrect-passphrase' } })).status, 401)
  assert.equal((await call('/profile', { method: 'PATCH', cookie, body: { name: 'Updated', phone: '555' }, origin: 'https://attacker.example' })).status, 403)
  assert.equal((await call('/profile', { method: 'PATCH', cookie, body: { name: 'Updated', phone: '555' }, customHeader: false })).status, 403)
  assert.equal((await call('/profile', { method: 'PATCH', cookie, body: { name: 'X', phone: 'not-a-phone' } })).status, 400)
  assert.equal((await call('/profile', { method: 'PATCH', cookie, body: { name: 'Updated', phone: '555', role: 'admin' } })).status, 400)
  const updated = await call('/profile', { method: 'PATCH', cookie, body: { name: 'Updated Fictional Staff', phone: '+63 900 000 0000' } })
  assert.equal(updated.status, 200)
  assert.equal((await (await call('/me', { cookie })).json()).user.name, 'Updated Fictional Staff')
  assert.equal((await User.findById(data.user.id)).phone, '+63 900 000 0000')

  const tampered = `${cookie.slice(0, -1)}!`
  assert.equal((await call('/me', { cookie: tampered })).status, 401)
  const expired = jwt.sign({}, config.jwtSecret, { subject: data.user.id, jwtid: randomBytes(32).toString('hex'), issuer: 'clinic-api', audience: 'clinic-web', expiresIn: -1 })
  assert.equal((await call('/me', { cookie: `clinic_session=${expired}` })).status, 401)
  assert.equal((await call('/logout', { method: 'POST', cookie, body: {} })).status, 204)
  assert.equal((await call('/me', { cookie })).status, 401, 'a logged-out token must not work when replayed')
  assert.equal(await Session.countDocuments(), 0)

  const login = await call('/login', { method: 'POST', body: { email: 'STAFF@EXAMPLE.COM', password: registration.password } })
  assert.equal(login.status, 200)
  const nextCookie = login.headers.get('set-cookie').split(';')[0]
  assert.equal((await (await call('/me', { cookie: nextCookie })).json()).user.name, 'Updated Fictional Staff')
  assert.equal((await call('/logout', { method: 'POST', cookie: nextCookie, body: {} })).status, 204)

  for (let attempt = 0; attempt < 21; attempt++) {
    const result = await call('/login', { method: 'POST', body: {} })
    if (attempt === 20) assert.equal(result.status, 429)
  }
})
